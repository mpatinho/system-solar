export const BODY_BY_ID = Object.fromEntries(BODIES.map((b) => [b.id, b]));

export const PLANET_IDS = ['mercurio', 'venus', 'tierra', 'marte', 'jupiter', 'saturno', 'urano', 'neptuno'];

export function shortName(id) {
  const b = BODY_BY_ID[id];
  return b ? b.short || b.name : id;
}

// Texto para leer en voz alta.
export function speechText(b) {
  const facts = b.facts.map(([k, v]) => `${k}: ${v}.`).join(' ');
  return `${b.name}. ${b.subtitle.replaceAll('·', ',')}. ${facts} Para el examen: ${b.exam.join(' ')} Curiosidad: ${b.curiosity}`;
}
